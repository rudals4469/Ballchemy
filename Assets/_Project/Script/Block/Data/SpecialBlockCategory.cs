public enum SpecialBlockCategory
{
    None = 0,

    /*
     * 파괴하면 플레이어에게 일반적인 이득을 주는 블록.
     * 예: 회복, 재화, 폭발
     */
    Reward = 1,

    /*
     * 파괴하면 플레이어에게 손해가 되는 블록.
     * 예: 저주, 수리, 쉴드
     */
    DangerOnDestroy = 2,

    /*
     * 파괴하지 못했을 때 손해를 주는 블록.
     * 예: 공 봉인
     */
    Urgent = 3,

    /*
     * 기존 전투 중 공 추가 블록.
     *
     * 방 클리어 보상 시스템으로 이전하는 동안
     * 신규 전투 배치에서는 생성하지 않는다.
     * 기존 프리팹과 스크립트는 단계적으로 제거한다.
     */
    LegacyAddBall = 4,

    /*
     * 살아 있는 동안 지정된 적 블록을 완전 보호하는 파괴 가능 특수 블록.
     */
    Guardian = 5
}
